-- Tabla de objetos del pañol
CREATE TABLE public.objetos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    descripcion TEXT,
    especialidad TEXT NOT NULL,
    sector TEXT,
    estante TEXT,
    armario TEXT,
    cajon TEXT,
    observaciones TEXT,
    imagen_url TEXT,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

-- Tabla de perfiles de usuarios
CREATE TABLE public.perfiles (
    id UUID PRIMARY KEY,
    nombre TEXT NOT NULL,
    apellido TEXT NOT NULL,
    tipo_integrante TEXT NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),

    CONSTRAINT perfiles_id_fkey
        FOREIGN KEY (id)
        REFERENCES auth.users(id)
        ON DELETE CASCADE,

    CONSTRAINT perfiles_tipo_integrante_check
        CHECK (
            tipo_integrante IN (
                'profesor',
                'preceptor',
                'directivo',
                'pañolero',
                'otro'
            )
        )
);
